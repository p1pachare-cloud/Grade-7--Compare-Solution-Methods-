import { Q, qAdd, qSub, qMul, qDiv, qEq, qToNumber } from '../src/engine/exact.js';
import { mulberry32 } from '../src/engine/rng.js';
import { GENERATORS } from '../src/engine/generators/index.js';
import { makeContext } from '../src/engine/context.js';
import { verify } from '../src/engine/verify.js';
import { buildSession, buildWorld } from '../src/engine/buildWorld.js';
import { NARRATION } from '../src/data/narrationSource.js';
import { toDisplay, toSpeech } from '../src/utils/mathText.js';
import { checkBadges } from '../src/utils/badgeEngine.js';
import { setMuted, isAudioMuted } from '../src/utils/audio.js';

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    passed++;
  } else {
    failed++;
    console.error(`❌ FAILED: ${message}`);
  }
}

console.log('--- Running Method Masters Test Suite ---\n');

// 1. Exact Arithmetic Tests
console.log('1. Testing exact rational arithmetic...');
const half = Q(1, 2);
const third = Q(1, 3);
const sum = qAdd(half, third);
assert(qEq(sum, Q(5, 6)), '1/2 + 1/3 = 5/6');

const prod = qMul(half, third);
assert(qEq(prod, Q(1, 6)), '1/2 * 1/3 = 1/6');

const div = qDiv(half, third);
assert(qEq(div, Q(3, 2)), '1/2 / 1/3 = 3/2');
assert(qToNumber(div) === 1.5, 'qToNumber(3/2) === 1.5');

// 2. Question Generator Property Tests (10 types x 3 tiers x 50 iterations = 1500 questions)
console.log('\n2. Testing all 10 procedural generators with seeded PRNG...');
const typeKeys = Object.keys(GENERATORS);

for (const key of typeKeys) {
  const gen = GENERATORS[key];
  let genPass = 0;
  for (let tier = 1; tier <= 3; tier++) {
    for (let i = 0; i < 30; i++) {
      const rng = mulberry32(1000 * tier + i);
      const ctx = makeContext(rng);
      const q = gen(rng, tier, ctx);
      const isValid = verify(q);
      if (isValid) genPass++;
      else console.error(`Invalid question generated by ${key} tier ${tier}:`, q);
    }
  }
  assert(genPass === 90, `Generator ${key} passed 90/90 property tests`);
}

// 3. Full 100-Question Session Generation & Deduplication
console.log('\n3. Testing full 100-question session generation...');
const session = buildSession(42);
assert(session.length === 100, `Session generated exactly 100 questions (got ${session.length})`);

const signatures = new Set(session.map((q) => q.signature));
assert(signatures.size === 100, `All 100 questions have unique signatures (0 repeats within session)`);

const allVerified = session.every((q) => verify(q));
assert(allVerified, 'All 100 session questions pass dual-solver verification');

// 4. Audio Pipeline Content Policy Tests
console.log('\n4. Testing audio content policy & speech parity...');
let audioValid = true;
for (const item of NARRATION) {
  const disp = toDisplay(item.src);
  const speech = toSpeech(item.src);
  if (!disp || !speech) {
    audioValid = false;
    console.error('Invalid narration item:', item);
  }
  // Check that titles/headings are not present
  if (item.id.includes('title') || item.id.includes('heading')) {
    audioValid = false;
    console.error('Violated title narration policy:', item.id);
  }
}
assert(audioValid, 'All narration strings adhere strictly to speech parity & paragraph/question-only policy');

// 5. Badge Engine Tests
console.log('\n5. Testing gamification badge engine...');
const mockState = {
  phaseComplete: { wonder: true, story: true, simulate: true, practice: true, reflect: true },
  completedStations: [true, true, true],
  worldScores: [10, 8, 9, 7, 8, 9, 8, 9, 8, 10], // sum = 86 >= 80, has 10
  maxStreak: 12,
  unlockedBadges: [],
  errorDetectiveCount: 5,
  efficiencyCount: 5,
};

const unlocked = checkBadges(mockState);
assert(unlocked.length === 8, `All 8 badges unlocked under complete conditions (got ${unlocked.length})`);

console.log('\n6. Testing audio mute controller...');
setMuted(false);
assert(!isAudioMuted(), 'Audio muted initial flag is false');
setMuted(true);
assert(isAudioMuted(), 'Audio muted flag set to true');
setMuted(false);
assert(!isAudioMuted(), 'Audio unmuted flag restored to false');

console.log(`\n========================================`);
console.log(`Test Results: ${passed} PASSED, ${failed} FAILED`);
console.log(`========================================\n`);

if (failed > 0) {
  process.exit(1);
} else {
  process.exit(0);
}

